#!/usr/bin/env node
// Keep Noto Sans TC glyphs used by the app shell available offline without
// precaching every Unicode subset. User-provided text falls back to OS fonts.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontRoot = path.join(root, 'node_modules/@fontsource-variable/noto-sans-tc');
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => entry.isDirectory()
    ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]);
}
const files = [...walk(path.join(root, 'src')).filter((file) => /\.(js|jsx)$/.test(file)),
  path.join(root, 'index.html'), path.join(root, 'public/manifest.webmanifest')];
const chars = new Set([...files.map((file) => readFileSync(file, 'utf8')).join('\n')].map((char) => char.codePointAt(0)));
const original = readFileSync(path.join(fontRoot, 'index.css'), 'utf8');
const blocks = [...original.matchAll(/\/\* ([^*]+) \*\/\s*@font-face\s*\{([^}]+)\}/g)];
const selected = blocks.filter((match) => {
  const raw = match[2].match(/unicode-range:\s*([^;]+)/)?.[1];
  if (!raw) throw new Error(`Font subset has no unicode-range: ${match[1]}`);
  const ranges = raw.split(',').map((part) => part.trim().replace(/^U\+/i, '').split('-').map((hex) => parseInt(hex, 16)));
  return [...chars].some((char) => ranges.some(([lo, hi = lo]) => char >= lo && char <= hi));
}).map((match) => match[0].replaceAll('./files/', '../node_modules/@fontsource-variable/noto-sans-tc/files/'));
if (!selected.length) throw new Error('No usable Noto Sans TC subsets found.');
const result = `/* Generated by scripts/sync-font-subsets.mjs; do not edit. OFL-1.1; see public/third-party-licenses.txt. */\n${selected.join('\n\n')}\n`;
const out = path.join(root, 'src/font-subsets.css');
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== result) { console.error('Font subset manifest is stale; run npm run fonts:sync.'); process.exit(1); }
} else writeFileSync(out, result);
console.log(`Noto Sans TC: ${selected.length}/${blocks.length} subsets for offline app text; other characters use device fonts.`);
